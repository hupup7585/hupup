// Builds src/lib/config-usage.generated.ts: for each Admin setting, the source files that read it (Phase 2,
// "show which other settings, screens or workflows use a setting before it is changed"). Run: node scripts/config-usage.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const settings = readFileSync("src/lib/settings.ts", "utf8");
const block = settings.slice(settings.indexOf("SETTING_DEFAULTS = {"), settings.indexOf("} as const", settings.indexOf("SETTING_DEFAULTS = {")));
// Every key, also several to a line (ringAfterTo0 and friends), and the phone timers spread in from timers.ts
const keys = [
  ...[...block.matchAll(/(?:^|,)\s*([a-zA-Z][a-zA-Z0-9]*): (?:"|`|true|false)/gm)].map((m) => m[1]),
  ...[...readFileSync("src/lib/ivr/timers.ts", "utf8").matchAll(/key: "(timer[A-Za-z]+)"/g)].map((m) => m[1]),
];
const files = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? files(join(d, f)) : /\.(ts|tsx)$/.test(f) ? [join(d, f)] : []));
// The settings list itself, its explanations, its registry and its rules name every setting: they are not uses (M4)
const src = files("src").filter((f) => !/(lib\/settings|config-usage\.generated|config-explanations|config-registry|setting-rules)\.ts$/.test(f)).map((f) => [f, readFileSync(f, "utf8")]);
const out = {};
// A setting is used where its name appears, or where the code builds its name from a pattern (Hark's review M4):
// \`ringAttempts\${k}\` reads ringAttempts0 to ringAttempts8; \`music\${place}\` reads musicStaffWait.
const patterns = (k) => [...(/\d$/.test(k) ? [k.replace(/\d+$/, "")] : []), ...[...k.matchAll(/[A-Z]/g)].map((m) => k.slice(0, m.index))].filter((p) => p.length > 3);
for (const k of keys)
  out[k] = src
    .filter(([, s]) => new RegExp(`\\b${k}\\b`).test(s) || patterns(k).some((p) => s.includes(`\`${p}\${`)))
    .map(([f]) => f.replace(/^src\//, ""))
    .sort();
const text = `/* Generated by scripts/config-usage.mjs: where each Admin setting is read. Do not edit by hand. */\nexport const CONFIG_USAGE: Record<string, string[]> = ${JSON.stringify(out, null, 1)};\n`;
// --check: fail if the file is out of date (a test runs this)
if (process.argv.includes("--check")) {
  if (readFileSync("src/lib/config-usage.generated.ts", "utf8") !== text) {
    console.error("config-usage.generated.ts is out of date: run node scripts/config-usage.mjs");
    process.exit(1);
  }
} else writeFileSync("src/lib/config-usage.generated.ts", text);
console.log(keys.length, "settings");
