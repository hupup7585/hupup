// Which phone screens no call can reach any more (Hark's Phases 1-3 review, item 14). Follows every step a call can
// go to, starting from where Twilio enters (incoming calls, and steps named from outside the phone flow), through
// back(...), url(...), repeatMenu(...) and toStep(...) in each step's code. Writes src/lib/ivr/unreached.generated.ts;
// run with --check to fail when the file is out of date.
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

const flow = readFileSync("src/lib/ivr/flow.ts", "utf8") + "\n" + readFileSync("src/lib/ivr/vmail.ts", "utf8");
const screens = readFileSync("src/lib/ivr/screens.ts", "utf8");
const screenNames = [...screens.matchAll(/^  "([^"]+)": \{\n    "choice"/gm)].map((m) => m[1]);
const choiceOf = Object.fromEntries([...screens.matchAll(/^  "([^"]+)": \{\n    "choice": "([^"]*)"/gm)].map((m) => [m[1], m[2]]));

// handler bodies: from `  "name"(ctx` / `  async "name"(ctx` / `  name(ctx` to the next handler start
const starts = [...flow.matchAll(/^  (?:async )?"?([a-z][a-z0-9-]*)"?\(ctx[,)]/gm)].map((m) => ({ name: m[1], at: m.index }));
const body = {};
starts.forEach((s, i) => { body[s.name] = flow.slice(s.at, i + 1 < starts.length ? starts[i + 1].at : flow.length); });
const names = new Set(Object.keys(body));
const refsIn = (text) => new Set([...text.matchAll(/(?:back|url|repeatMenu|toStep)\(\s*(?:vr|g|target)?\s*,?\s*(?:ctx\s*,\s*)?"([a-z][a-z0-9-]*)"/g)].map((m) => m[1]).filter((n) => names.has(n)));

// steps named from anywhere outside the handler bodies (helpers in flow.ts, other modules, API routes) are entries
const outsideFlow = (() => {
  const files = [];
  const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (/\.(ts|tsx)$/.test(f) && !/flow\.ts$|vmail\.ts$|screens\.ts$|\.generated\.ts$/.test(p)) files.push(p); } };
  walk("src");
  // only files that send a call to a phone step (they build /api/voice/<step> links); Admin pages that merely list steps do not count
  return files.map((f) => readFileSync(f, "utf8")).filter((t) => t.includes("/api/voice/")).join("\n");
})();
let helpers = flow;
for (const s of starts) helpers = helpers.replace(body[s.name], "");
const entries = new Set(["incoming", "menu", ...refsIn(helpers), ...[...outsideFlow.matchAll(/\/api\/voice\/([a-z][a-z0-9-]*)/g)].map((m) => m[1]).filter((n) => names.has(n))]);
const seen = new Set();
const todo = [...entries];
while (todo.length) {
  const n = todo.pop();
  if (seen.has(n) || !body[n]) continue;
  seen.add(n);
  for (const r of refsIn(body[n])) todo.push(r);
}
const unreached = screenNames.filter((s) => !seen.has(s) && !seen.has(choiceOf[s])).sort();
const out = `// Generated by scripts/screen-reach.mjs: phone screens no call can reach any more (kept so old links still work).\nexport const UNREACHED_SCREENS: readonly string[] = ${JSON.stringify(unreached)};\n`;
const file = "src/lib/ivr/unreached.generated.ts";
if (process.argv.includes("--check")) {
  if (readFileSync(file, "utf8") !== out) { console.error(`${file} is out of date: run node scripts/screen-reach.mjs`); process.exit(1); }
} else writeFileSync(file, out);
console.log(unreached.length, "not reached:", unreached.join(", "));
