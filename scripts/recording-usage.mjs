// Builds src/lib/recording-usage.generated.ts: for each phone line (PROMPTS key), the source files that play or name it
// (Admin handoff Phase 3, section 7: "screens using it and whether it is unused"). Run: node scripts/recording-usage.mjs
// --check fails when the file is out of date (a test runs this).
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const OUT = "src/lib/recording-usage.generated.ts";
const prompts = readFileSync("src/lib/ivr/prompts.ts", "utf8");
const block = prompts.slice(prompts.indexOf("export const PROMPTS"));
const keys = [...new Set([...block.matchAll(/^  ([a-z0-9_]+): \{/gm)].map((m) => m[1]))].sort();
const files = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? files(join(d, f)) : /\.(ts|tsx)$/.test(f) ? [join(d, f)] : []));
const skip = ["src/lib/ivr/prompts.ts", OUT, "src/lib/ivr/screens.ts", "src/lib/config-explanations.ts"];
const src = files("src").filter((f) => !skip.includes(f)).map((f) => [f, readFileSync(f, "utf8")]);
const out = {};
// A line is used when its exact name is in the code, or when the code builds names from its prefix
// (for example \`balloon_name_\${n}\` or \`lset_\${...}\`).
const prefixes = (k) => [...k.matchAll(/_/g)].map((m) => k.slice(0, m.index + 1));
for (const k of keys)
  out[k] = src
    .filter(([, s]) => s.includes(`"${k}"`) || s.includes(`'${k}'`) || s.includes(`\`${k}\``) || prefixes(k).some((p) => p.length > 3 && s.includes(`\`${p}\${`)))
    .map(([f]) => f.replace(/^src\//, ""))
    .sort();
const text = `/* Generated by scripts/recording-usage.mjs: the source files that play or name each phone line. Do not edit by hand. */\nexport const RECORDING_USAGE: Record<string, string[]> = ${JSON.stringify(out, null, 1)};\n`;
if (process.argv.includes("--check")) {
  let now = "";
  try { now = readFileSync(OUT, "utf8"); } catch {}
  if (now !== text) { console.error(`${OUT} is out of date: run node scripts/recording-usage.mjs`); process.exit(1); }
} else writeFileSync(OUT, text);
console.log(keys.length, "lines");
